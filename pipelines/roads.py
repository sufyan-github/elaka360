"""Named roads per union, pourashava, city ward or city corporation, from OpenStreetMap (data/sources/
osm_localities_2026/roads.csv: named highways sampled every ~250 m).

Each sampled point is placed in the most specific area with a boundary (ward, union, pourashava, city corporation);
a road's length is shared between the areas in proportion to its points there. Ways with the same name (or ref) and
road class in one area are listed once. Community data (ODbL): shown as unverified.

Writes db/seed/roads/<division>.sql (table area_roads, migration 0011) and data/seed/geo/roads/<division>.csv.
build_seed.py calls write_all(rows, SRC_IDS) with the admin areas and their boundaries in memory.
"""
import csv, os, shutil
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROADS = os.path.join(ROOT, "data", "sources", "osm_localities_2026", "roads.csv")
CSV_DIR = os.path.join(ROOT, "data", "seed", "geo", "roads")
SQL_DIR = os.path.join(ROOT, "db", "seed", "roads")
SOURCE = "OSM_LOCALITIES_2026"
CONTAINERS = ("ward", "union", "pourashava", "city_corporation")
COLS = ["area_id", "name", "name_bn", "highway", "ref", "length_m", "osm_ids"]


def lit(v):
    if v is None or v == "":
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def build(rows):
    from collected import PolygonIndex
    polys = [r for r in rows if r.get("_boundary") and r["level"] in CONTAINERS]
    rank = {lvl: i for i, lvl in enumerate(CONTAINERS)}
    index = PolygonIndex([{"type": "Feature", "geometry": r["_boundary"], "properties": {"id": r["id"], "level": r["level"]}} for r in polys])
    agg = {}
    stats = Counter()
    for r in csv.DictReader(open(ROADS, encoding="utf-8")):
        pts = [tuple(map(float, p.split())) for p in r["points"].split(";") if p]
        where = Counter()
        for lon, lat in pts:
            hits = index.find(lon, lat)
            if hits:
                where[min(hits, key=lambda f: rank[f["properties"]["level"]])["properties"]["id"]] += 1
        if not where:
            stats["outside"] += 1
            continue
        stats["roads"] += 1
        label = r["name"] or r["ref"]
        for area_id, n in where.items():
            k = (area_id, label.casefold(), r["highway"])
            a = agg.setdefault(k, dict(area_id=area_id, name=r["name"] or None, name_bn=r["name_bn"] or None, highway=r["highway"],
                                       ref=r["ref"] or None, length_m=0.0, osm_ids=[]))
            a["length_m"] += int(r["length_m"]) * n / len(pts)
            a["osm_ids"].append(int(r["osm_id"]))
            a["name_bn"] = a["name_bn"] or r["name_bn"] or None
    out = []
    for a in agg.values():
        a["length_m"] = max(1, round(a["length_m"]))
        a["osm_ids"] = sorted(set(a["osm_ids"]))
        out.append(a)
    out.sort(key=lambda a: (a["area_id"], a["highway"], a["name"] or a["ref"] or ""))
    stats["area_roads"] = len(out)
    return out, stats


def write_all(rows, src_ids):
    for d in (CSV_DIR, SQL_DIR):
        shutil.rmtree(d, ignore_errors=True)
    if not os.path.isfile(ROADS):
        return {"skipped": "no roads.csv"}
    items, stats = build(rows)
    os.makedirs(CSV_DIR); os.makedirs(SQL_DIR)
    div_of = {r["id"]: r["path"].split("/")[0] for r in rows}
    by_div = defaultdict(list)
    for a in items:
        by_div[div_of[a["area_id"]]].append(a)
    sid = src_ids.get(SOURCE)          # registered by build_seed.py; absent only in a standalone run on an older build
    for div, lst in sorted(by_div.items()):
        with open(os.path.join(CSV_DIR, f"{div}.csv"), "w", newline="", encoding="utf-8-sig") as f:
            w = csv.DictWriter(f, fieldnames=COLS); w.writeheader()
            w.writerows(dict(a, osm_ids=" ".join(map(str, a["osm_ids"]))) for a in lst)
        with open(os.path.join(SQL_DIR, f"{div}.sql"), "w", encoding="utf-8") as f:
            f.write("-- Elaka360 seed data. Generated by pipelines/roads.py; loaded through db/seed/seed.sql.\n")
            for i in range(0, len(lst), 500):
                vals = ",\n".join("(" + ",".join([str(a["area_id"]), lit(a["name"]), lit(a["name_bn"]), lit(a["highway"]), lit(a["ref"]),
                                                  str(a["length_m"]), "'{" + ",".join(map(str, a["osm_ids"])) + "}'", lit(sid)]) + ")"
                                  for a in lst[i:i + 500])
                f.write(f"INSERT INTO area_roads(area_id,name,name_bn,highway,ref,length_m,osm_ids,data_source_id) VALUES\n{vals};\n")
    return dict(stats, divisions=sorted(by_div))


if __name__ == "__main__":
    # standalone: the built admin areas, with boundaries from the database at DATABASE_URL (see localities._load_built)
    import json, sys
    sys.path.insert(0, os.path.dirname(__file__))
    import localities
    print(json.dumps(write_all(*localities._load_built()), indent=1))
